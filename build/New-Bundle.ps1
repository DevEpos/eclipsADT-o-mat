#Requires -Version 7.0
<#
.SYNOPSIS
    Builds the single-file release distributions of eclipsADT-o-Mat.

.DESCRIPTION
    Takes Setup-EclipsAdtOMat.ps1 and produces one self-contained script by
    - inlining every dot-sourced lib/*.ps1 file (bundled-libs region),
    - embedding catalog.json as a here-string (bundled-catalog region),
    - injecting the release tag into $script:DistributionVersion.
    The result is parse-validated before it is written. A double-clickable
    .cmd polyglot variant (batch launcher header + same payload) is written
    alongside the .ps1.

.PARAMETER Version
    Release tag to embed, e.g. 'v1.0.0'. Must be a (v-prefixed) semver.

.PARAMETER OutputPath
    Path of the bundled script to write. Defaults to 'dist/eclipsADT-o-mat.ps1'
    relative to the repository root.

.EXAMPLE
    ./build/New-Bundle.ps1 -Version v1.0.0
#>
[CmdletBinding()]
param(
    [Parameter(Mandatory)]
    [ValidatePattern('^[vV]?\d+\.\d+\.\d+')]
    [string]$Version,

    [string]$OutputPath
)

$ErrorActionPreference = 'Stop'
$repoRoot = Split-Path -Parent $PSScriptRoot
if (-not $OutputPath) { $OutputPath = Join-Path $repoRoot 'dist/eclipsADT-o-mat.ps1' }

function Set-RegionContent {
    param(
        [Parameter(Mandatory)] [string]$Text,
        [Parameter(Mandatory)] [string]$Name,
        [Parameter(Mandatory)] [string]$Replacement
    )

    $startMarker = "#region $Name"
    $endMarker = "#endregion $Name"
    $startIndex = $Text.IndexOf($startMarker)
    $endIndex = $Text.IndexOf($endMarker)
    if ($startIndex -lt 0 -or $endIndex -lt 0) {
        throw "Region '$Name' not found in the main script."
    }
    return [PSCustomObject]@{
        Text    = $Text.Substring(0, $startIndex) + $Replacement + $Text.Substring($endIndex + $endMarker.Length)
        Content = $Text.Substring($startIndex, $endIndex - $startIndex)
    }
}

$mainScriptPath = Join-Path $repoRoot 'Setup-EclipsAdtOMat.ps1'
$text = Get-Content -LiteralPath $mainScriptPath -Raw

# --- Inline the dot-sourced lib scripts ----------------------------------------
$libRegionStart = $text.IndexOf('#region bundled-libs')
$libRegionEnd = $text.IndexOf('#endregion bundled-libs')
if ($libRegionStart -lt 0 -or $libRegionEnd -lt 0) { throw "Region 'bundled-libs' not found in the main script." }
$libRegion = $text.Substring($libRegionStart, $libRegionEnd - $libRegionStart)

$libNames = [regex]::Matches($libRegion, "lib\\([A-Za-z0-9]+\.ps1)") | ForEach-Object { $_.Groups[1].Value }
if ($libNames.Count -eq 0) { throw "No dot-sourced lib scripts found in the 'bundled-libs' region." }

$inlined = [System.Text.StringBuilder]::new()
foreach ($libName in $libNames) {
    $libPath = Join-Path $repoRoot 'lib' $libName
    $libText = (Get-Content -LiteralPath $libPath -Raw).TrimEnd()
    # Strip #Requires lines; the main script's own #Requires stays authoritative.
    $libText = ($libText -split "`r?`n" | Where-Object { $_ -notmatch '^\s*#Requires\s' }) -join [Environment]::NewLine
    [void]$inlined.AppendLine("# ===== inlined: lib/$libName =====")
    [void]$inlined.AppendLine($libText)
    [void]$inlined.AppendLine()
    Write-Host "Inlined lib/$libName"
}

$result = Set-RegionContent -Text $text -Name 'bundled-libs' -Replacement $inlined.ToString().TrimEnd()
$text = $result.Text

# --- Embed catalog.json ---------------------------------------------------------
$catalogJson = (Get-Content -LiteralPath (Join-Path $repoRoot 'catalog.json') -Raw).TrimEnd()
if ($catalogJson -split "`r?`n" | Where-Object { $_ -match "^'@" }) {
    throw "catalog.json contains a line starting with '@ which would terminate the here-string."
}
$null = $catalogJson | ConvertFrom-Json  # fail fast on invalid JSON

$catalogReplacement = @"
`$catalog = @'
$catalogJson
'@ | ConvertFrom-Json
"@
$result = Set-RegionContent -Text $text -Name 'bundled-catalog' -Replacement $catalogReplacement.TrimEnd()
$text = $result.Text
Write-Host "Embedded catalog.json"

# --- Inject the release version --------------------------------------------------
$versionMarker = '$script:DistributionVersion = $null'
if (-not $text.Contains($versionMarker)) {
    throw "Version marker '$versionMarker' not found in the main script."
}
$text = $text.Replace($versionMarker, "`$script:DistributionVersion = '$Version' # generated by build/New-Bundle.ps1")
Write-Host "Injected version $Version"

# --- Validate & write -------------------------------------------------------------
$tokens = $null
$parseErrors = $null
[System.Management.Automation.Language.Parser]::ParseInput($text, [ref]$tokens, [ref]$parseErrors) | Out-Null
if ($parseErrors -and $parseErrors.Count -gt 0) {
    $parseErrors | ForEach-Object { Write-Host "  $($_.Extent.StartLineNumber): $($_.Message)" -ForegroundColor Red }
    throw "Bundled script has $($parseErrors.Count) parse error(s)."
}
if ($text -match "Join-Path \`$scriptRoot 'lib\\") {
    throw "Bundled script still contains dot-source references to lib scripts."
}

$outputDir = Split-Path -Parent $OutputPath
if ($outputDir -and -not (Test-Path -LiteralPath $outputDir)) {
    New-Item -ItemType Directory -Force -Path $outputDir | Out-Null
}
[System.IO.File]::WriteAllText($OutputPath, $text, [System.Text.UTF8Encoding]::new($true))
Write-Host "Wrote $OutputPath ($([math]::Round((Get-Item -LiteralPath $OutputPath).Length / 1KB)) KB)" -ForegroundColor Green

# --- Double-clickable .cmd polyglot -----------------------------------------------
# cmd.exe runs the batch header (no execution policy applies) and relaunches the
# file's own content via pwsh; PowerShell sees the header as a <# comment #>.
$cmdHeaderLines = @(
    '<# : eclipsADT-o-Mat launcher - the batch header below is a PowerShell comment.'
    '@echo off & setlocal'
    'where pwsh >nul 2>&1'
    'if errorlevel 1 ('
    '    echo PowerShell 7 ^(pwsh.exe^) was not found.'
    '    echo Install it from https://aka.ms/powershell'
    '    if not "%ECLIPSADT_NO_PAUSE%"=="1" pause'
    '    exit /b 1'
    ')'
    'set "ECLIPSADT_LAUNCHER=%~f0"'
    'set "ECLIPSADT_RUN=%TEMP%\eclipsADT-o-Mat-run-%RANDOM%%RANDOM%.ps1"'
    'copy /y "%~f0" "%ECLIPSADT_RUN%" >nul'
    'pwsh -NoLogo -NoProfile -ExecutionPolicy Bypass -File "%ECLIPSADT_RUN%" %*'
    'set "exitCode=%ERRORLEVEL%"'
    'del "%ECLIPSADT_RUN%" >nul 2>&1'
    'if not "%exitCode%"=="0" echo eclipsADT-o-Mat exited with code %exitCode%.'
    'if not "%ECLIPSADT_NO_PAUSE%"=="1" pause'
    'exit /b %exitCode%'
    '#>'
    ''
)
# CRLF is required for cmd.exe; no BOM, because cmd.exe chokes on BOM bytes.
$cmdText = ($cmdHeaderLines -join "`r`n") + $text
$cmdOutputPath = [System.IO.Path]::ChangeExtension($OutputPath, '.cmd')

$parseErrors = $null
[System.Management.Automation.Language.Parser]::ParseInput($cmdText, [ref]$tokens, [ref]$parseErrors) | Out-Null
if ($parseErrors -and $parseErrors.Count -gt 0) {
    $parseErrors | ForEach-Object { Write-Host "  $($_.Extent.StartLineNumber): $($_.Message)" -ForegroundColor Red }
    throw "Bundled .cmd launcher has $($parseErrors.Count) parse error(s)."
}
[System.IO.File]::WriteAllText($cmdOutputPath, $cmdText, [System.Text.UTF8Encoding]::new($false))
Write-Host "Wrote $cmdOutputPath ($([math]::Round((Get-Item -LiteralPath $cmdOutputPath).Length / 1KB)) KB)" -ForegroundColor Green
